'''
Conditional Statements in Python

Conditional statements are used to make decisions in a program.
They check a condition and run different code based on whether the condition is True or False.

1. if Statement
Syntax:
if condition:
    # code to run if condition is True

Example:
marks = 85

if marks >= 50:
    print("Pass")

2. if-else Statement
Syntax:
if condition:
    # code to run if condition is True
else:
    # code to run if condition is False

Example:
age = 18

if age >= 18:
    print("You are an adult")
else:
    print("You are a minor")

3. if-elif-else Statement
Syntax:
if condition1:
    # code
elif condition2:
    # code
else:
    # code

Example:
score = 75

if score >= 90:
    print("Grade A")
elif score >= 70:
    print("Grade B")
else:
    print("Grade C")
'''

