'''
While Loop in Python

A while loop repeats a block of code as long as a condition is True.
It is useful when you do not know in advance how many times the loop should run.

Syntax:
while condition:
    # code to be executed

Example:
count = 1

while count <= 5:
    print(count)
    count += 1

Explanation:
- The loop starts with count = 1.
- It prints the value and increases it by 1 each time.
- The loop stops when count becomes 6.
'''
