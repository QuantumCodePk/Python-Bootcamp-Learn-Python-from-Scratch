'''
Infinite Loop in Python

An infinite loop is a loop that keeps running forever because its condition never becomes False.
It can happen accidentally, so it should be used carefully.

Syntax:
while True:
    # code to repeat forever

Example:
while True:
    print("This will run forever")

Note:
- This loop will never stop on its own.
- It is usually stopped by pressing Ctrl + C in the terminal.
- In real programs, infinite loops are avoided unless they are meant to run continuously.
'''
