''' 
we can use comparison operators to, you guessed it, compare the values of variables. They will always return a boolean value, which is either True or False. 
There are six of them:

Equal: ==
Not equal: !=
Greater than: >
Less than: <
Greater than or equal: >=
Less than or equal: <=

'''

a = 3
b = 5

print(a == b) # Equal
print(a != b) # Not equal
print(a > b) # Greater than
print(a < b) # Less than
print(a >= b) # Greater than or equal to
print(a <= b) # Less than or equal to